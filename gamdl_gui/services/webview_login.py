"""Standalone helper: sign in to Apple Music in a native webview and capture
the ``media-user-token`` cookie.

gamdl only needs a single cookie — ``media-user-token`` on ``.music.apple.com``
— so instead of asking the user to export a full ``cookies.txt`` we open the
real Apple Music sign-in page in the operating system's webview (WKWebView on
macOS, WebView2 on Windows, WebKitGTK on Linux), let them log in normally
(2FA included) and then read that one cookie.

Implementation notes:

* this module imports **no Qt** — it runs in its own process, because
  ``webview.start()`` owns the process main thread / event loop, which the Qt
  GUI has already taken;
* cookies are read with pywebview's own ``window.get_cookies()``, which
  internally marshals the WebKit/WebView2 call onto the **main thread**.  Doing
  it by hand is a trap: WebKit initialises itself lazily and ``SIGKILL``s the
  process if ``WKWebsiteDataStore`` is first touched from a worker thread;
* ``webview.start(func)`` runs ``func`` on a worker thread, which is fine as
  long as every webview call goes through pywebview's API.

Usage::

    python -m gamdl_gui.services.webview_login <output-cookies.txt>
"""

from __future__ import annotations

import argparse
import sys
import threading
import time
from pathlib import Path

LOGIN_URL = "https://music.apple.com/login"
COOKIE_NAME = "media-user-token"
COOKIE_DOMAIN = ".music.apple.com"
LOGIN_TIMEOUT = 15 * 60  # seconds the sign-in window may stay open


# ---------------------------------------------------------------------------
# cookies.txt writer
# ---------------------------------------------------------------------------
def write_cookies_file(path: str | Path, value: str, domain: str = COOKIE_DOMAIN) -> Path:
    """Write a Netscape cookies.txt containing just the media-user-token.

    The format was verified against ``http.cookiejar.MozillaCookieJar`` (what
    gamdl uses): the domain must keep its leading dot and the line must carry the
    ``#HttpOnly_`` prefix, otherwise the file fails to load.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    expires = int(time.time()) + 365 * 24 * 60 * 60
    content = "\n".join(
        [
            "# Netscape HTTP Cookie File",
            "# Generated by Gamdl GUI (webview sign-in).",
            f"#HttpOnly_{domain}\tTRUE\t/\tTRUE\t{expires}\t{COOKIE_NAME}\t{value}",
            "",
        ]
    )
    path.write_text(content, encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# cookie capture
# ---------------------------------------------------------------------------
def token_from_cookies(cookies) -> str | None:
    """Extract the cookie value from pywebview's ``get_cookies()`` result.

    ``get_cookies()`` returns a list of ``http.cookies.SimpleCookie``, one per
    cookie, each mapping name -> Morsel.
    """
    for cookie in cookies or []:
        try:
            items = list(cookie.items())
        except Exception:
            continue
        for name, morsel in items:
            if name != COOKIE_NAME:
                continue
            value = getattr(morsel, "value", morsel)
            if value:
                return str(value)
    return None


def capture_from_js(window) -> str | None:
    """Fallback for backends without ``get_cookies`` (e.g. edgechromium).

    Only works when the cookie is *not* HttpOnly.
    """
    try:
        raw = window.evaluate_js("document.cookie") or ""
    except Exception:
        return None
    for part in raw.split(";"):
        name, sep, value = part.strip().partition("=")
        if sep and name == COOKIE_NAME and value:
            return value
    return None


def capture_token(window) -> str | None:
    try:
        token = token_from_cookies(window.get_cookies())
    except Exception:
        token = None
    return token or capture_from_js(window)


# ---------------------------------------------------------------------------
# the webview app
# ---------------------------------------------------------------------------
def watch(window, finish, stop: threading.Event) -> None:
    deadline = time.time() + LOGIN_TIMEOUT
    while not stop.is_set() and time.time() < deadline:
        token = capture_token(window)
        if token:
            finish(token)
            return
        time.sleep(1.0)


def run_login(output_path: str) -> int:
    import webview  # imported here so `--help` works without pywebview

    result: dict[str, str | None] = {"value": None}
    stop = threading.Event()

    window = webview.create_window(
        "Sign in to Apple Music",
        LOGIN_URL,
        width=540,
        height=780,
        text_select=True,
    )

    def finish(token: str) -> None:
        result["value"] = token
        write_cookies_file(output_path, token)
        stop.set()
        try:
            window.destroy()
        except Exception:
            pass

    def on_start() -> None:
        # pywebview invokes this on a worker thread; all webview access below
        # goes through pywebview's API, which is main-thread safe.
        threading.Thread(target=watch, args=(window, finish, stop), daemon=True).start()

    # private_mode=False => cookies are persisted in the default data store, so
    # the user stays signed in next time.
    webview.start(on_start, private_mode=False)

    return 0 if result["value"] else 1


# ---------------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Apple Music webview sign-in for Gamdl GUI")
    parser.add_argument("output", help="path of the cookies.txt to write")
    args = parser.parse_args(argv)

    try:
        import webview  # noqa: F401
    except ImportError:
        print("pywebview is not installed (pip install pywebview)", file=sys.stderr)
        return 2

    return run_login(args.output)


if __name__ == "__main__":
    raise SystemExit(main())
